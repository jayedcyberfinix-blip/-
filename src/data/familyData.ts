// Helper maps
export const MEMBERS_MAP = new Map<string, FamilyMember>(
  FAMILY_MEMBERS.map((m) => [m.id, m])
);

export function getMemberById(id: string): FamilyMember | undefined {
  return MEMBERS_MAP.get(id);
}

export function getChildrenOf(parentId: string): FamilyMember[] {
  const parent = MEMBERS_MAP.get(parentId);
  if (!parent) return [];
  return parent.childrenIds
    .map((cid) => MEMBERS_MAP.get(cid))
    .filter((m): m is FamilyMember => !!m);
}

export function getLineagePath(memberId: string): FamilyMember[] {
  const path: FamilyMember[] = [];
  let curr: FamilyMember | undefined = MEMBERS_MAP.get(memberId);
  while (curr) {
    path.unshift(curr);
    if (!curr.parentId) break;
    curr = MEMBERS_MAP.get(curr.parentId);
  }
  return path;
}

export function getAllDescendantIds(memberId: string): string[] {
  const result: string[] = [];
  function recurse(id: string) {
    const member = MEMBERS_MAP.get(id);
    if (!member) return;
    for (const cid of member.childrenIds) {
      result.push(cid);
      recurse(cid);
    }
  }
  recurse(memberId);
  return result;
}
